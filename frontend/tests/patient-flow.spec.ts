import { expect, test } from '@playwright/test'

test('patient-first flow covers registration, route, document, call, booking and history', async ({ page }, testInfo) => {
  test.skip(!['mobile', 'desktop'].includes(testInfo.project.name), 'Critical flow is covered on mobile and desktop.')
  test.setTimeout(60_000)

  await page.goto('/')
  await page.getByRole('button', { name: /Открыть демо/ }).first().click()
  await expect(page.getByRole('heading', { name: 'Рабочий день' })).toBeVisible()
  await page.goto('/app/patients')
  await expect(page.getByRole('heading', { name: 'Пациенты' })).toBeVisible()

  await page.getByRole('link', { name: /Добавить пациента/ }).click()
  await expect(page.getByRole('heading', { name: 'Новый пациент' })).toBeVisible()
  await page.getByLabel('ФИО').fill('Алиса Сергеевна Тестова')
  await page.getByLabel('Дата рождения').fill('1990-03-14')
  await page.getByRole('button', { name: 'Зарегистрировать пациента' }).click()
  await expect(page.getByRole('heading', { name: 'Алиса Сергеевна Тестова' })).toBeVisible()
  await expect(page.getByText('P021', { exact: false }).first()).toBeVisible()

  await page.getByRole('button', { name: 'Создать демо-маршрут' }).click()
  await expect(page.getByText('Контроль после исследования')).toBeVisible()
  await page.getByRole('button', { name: 'Применить утверждённый план' }).click()
  await expect(page.getByRole('heading', { name: 'Маршрут пациента' })).toBeVisible()
  await expect(page.getByText('Консультация по результатам', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Контрольное исследование', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Помощник координатора')).toBeVisible()

  const fileInput = page.locator('.document-upload input[type="file"]')
  await page.getByLabel('Название').fill('Синтетический результат')
  await fileInput.setInputFiles({ name: 'synthetic-result.txt', mimeType: 'text/plain', buffer: Buffer.from('Synthetic RouteGuard document') })
  await page.getByRole('button', { name: 'Добавить документ' }).click()
  await expect(page.getByRole('status')).toHaveText('Синтетический документ добавлен')
  const documentLink = page.getByRole('link', { name: 'Открыть' }).last()
  await expect(documentLink).toBeVisible()
  const documentUrl = await documentLink.getAttribute('href')
  expect(documentUrl).toBeTruthy()
  const documentResponse = await page.request.get(documentUrl!)
  expect(documentResponse.status()).toBe(200)
  expect(await documentResponse.text()).toBe('Synthetic RouteGuard document')

  const assistant = page.locator('.detail-side .sticky')
  await assistant.getByLabel('Результат разговора').selectOption('reached')
  await assistant.getByLabel('Комментарий').fill('Пациент готов выбрать время')
  await assistant.getByRole('button', { name: 'Сохранить результат' }).click()
  await expect(assistant.getByRole('status')).toHaveText('Результат сохранён')

  const firstStep = page.locator('.step').filter({ hasText: 'Консультация по результатам' })
  await firstStep.getByRole('button', { name: 'Выбрать слот' }).click()
  await firstStep.locator('.slot-picker button').first().click()
  await expect(firstStep.getByRole('status')).toHaveText('Запись подтверждена')
  await firstStep.getByRole('button', { name: 'Отменить запись' }).click()
  await expect(firstStep.getByRole('status')).toContainText('шаг возвращён в работу')
  await expect(page.getByText(/Подобрать новую запись после отмены/).first()).toBeVisible()
  await firstStep.getByRole('button', { name: 'Выбрать слот' }).click()
  await firstStep.locator('.slot-picker button').first().click()
  await firstStep.getByRole('button', { name: 'Отметить выполненным' }).click()
  await expect(page.getByText('Шаг выполнен', { exact: true })).toBeVisible()

  const secondStep = page.locator('.step').filter({ hasText: 'Контрольное исследование' })
  await secondStep.getByRole('button', { name: 'Выбрать слот' }).click()
  await secondStep.locator('.slot-picker button').first().click()
  await secondStep.getByRole('button', { name: 'Отметить выполненным' }).click()
  await expect(secondStep.getByRole('button', { name: 'Добавить подтверждение' })).toBeVisible()
  await secondStep.getByRole('button', { name: 'Добавить подтверждение' }).click()
  await expect(page.getByText('Все обязательные шаги выполнены, маршрут завершён')).toBeVisible()

  const history = page.locator('section.panel').filter({ has: page.getByRole('heading', { name: 'История действий' }) })
  await expect(history.getByText(/Создан синтетический маршрут/)).toBeVisible()
  await expect(history.getByText(/Результат звонка/)).toBeVisible()
  await expect(history.getByText(/Запись: Отменена/)).toBeVisible()
  await expect(history.getByText(/Шаг выполнен/).first()).toBeVisible()

  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
})
