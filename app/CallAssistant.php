    private static function currentStep(array $route): ?array
    {
        foreach (($route['steps'] ?? []) as $step) {
            if (($step['status'] ?? '') !== 'completed') return $step;
        }
        return $route['steps'][0] ?? null;
    }

    private static function scheduledAppointment(array $route): ?array
    {
        foreach (($route['appointments'] ?? []) as $appointment) {
            if (($appointment['status'] ?? '') === 'scheduled') return $appointment;
        }
        return null;
    }
